    private static readonly Regex s_tagRegex = new(@"\[([\u4e00-\u9fa5a-zA-Z0-9]+)\]", RegexOptions.Compiled);

    /// <summary>
    /// 将文本中形如 [嘿哈]、[捂脸] 的微信表情代码转换为对应彩色 Emoji。
    /// </summary>
    public static string ReplaceWeChatEmojis(string? input)
    {
        if (string.IsNullOrEmpty(input)) return string.Empty;

        return s_tagRegex.Replace(input, m =>
        {
            if (s_emojiMap.TryGetValue(m.Value, out string? emoji))
            {
                return " " + emoji + " ";
            }
            return m.Value;
        });
    }

    /// <summary>
    /// 查询指定表情标签是否存在对应 Emoji。
    /// </summary>
    public static bool TryGetEmoji(string tag, out string? emoji) => s_emojiMap.TryGetValue(tag, out emoji);
